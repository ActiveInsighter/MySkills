import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const origin = process.argv[2] ?? 'https://myskills.any1.tech';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(origin);
  await page.getByRole('heading', { name: '把经验，写成下一次的起点。' }).waitFor();
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true });
  await page.getByRole('link', { name: '浏览 Skills', exact: true }).click();
  await page.getByRole('heading', { name: 'Skills', exact: true }).waitFor();
  await page.getByRole('link', { name: '任务拆解与验收', exact: true }).first().click();
  await page.getByRole('heading', { name: '任务拆解与验收', exact: true }).waitFor();
  assert.match(await page.title(), /任务拆解与验收/);
  await page.getByRole('button', { name: /搜索/ }).first().click();
  const input = page.getByRole('combobox', { name: '搜索 Skill' });
  await input.fill('任务');
  await page.getByRole('dialog').getByText('任务拆解与验收', { exact: true }).first().waitFor();
  await input.fill('Markdown');
  await page.getByRole('dialog').getByText('编写与发布', { exact: true }).first().waitFor();
  await page.keyboard.press('Escape');
  console.log('PASS client navigation to Chinese pages and Chinese/English search');
  await page.getByRole('button', { name: '复制 Markdown', exact: true }).click();
  const expected = await fetch(origin + '/docs/skills/任务拆解与验收.md').then(r => r.text());
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.equal(copied, expected);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载 Markdown', exact: true }).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), '任务拆解与验收.md');
  await download.saveAs('test-results/' + download.suggestedFilename());
  await page.screenshot({ path: 'test-results/skill-desktop.png', fullPage: true });
  console.log('PASS copy Markdown and browser download with Chinese filename');
  await page.goto(origin);
  await page.getByRole('button', { name: '切换主题', exact: true }).click();
  await page.waitForFunction(() => document.documentElement.classList.contains('dark'));
  await page.screenshot({ path: 'test-results/home-dark.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(origin + '/docs/skills/任务拆解与验收/');
  await page.getByRole('heading', { name: '任务拆解与验收', exact: true }).waitFor();
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, width: document.documentElement.scrollWidth }));
  assert.ok(dimensions.width <= dimensions.viewport, `Mobile page overflow: ${JSON.stringify(dimensions)}`);
  await page.screenshot({ path: 'test-results/skill-mobile-dark.png', fullPage: true });
  await page.evaluate(() => localStorage.setItem('theme', 'light'));
  await page.reload();
  await page.getByRole('heading', { name: '任务拆解与验收', exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/skill-mobile-light.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS dark theme, mobile layout, direct Chinese route, no JavaScript errors');
} finally { await browser.close(); }
